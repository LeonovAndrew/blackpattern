<h2>1. Общие положения</h2>
<p>Настоящая политика описывает порядок обработки персональных данных посетителей сайта Black Pattern. Оператор обрабатывает данные только для заранее определённых целей и принимает необходимые меры для их защиты.</p>

<h2>2. Какие данные могут обрабатываться</h2>
<ul>
    <li>имя, должность или роль пользователя;</li>
    <li>номер телефона и адрес электронной почты;</li>
    <li>содержание сообщения, переданного через форму;</li>
    <li>техническая информация: IP-адрес, URL страницы, referrer и UTM-метки.</li>
</ul>

<h2>3. Цели обработки</h2>
<p>Данные используются для обработки заявки, обратной связи, согласования консультации, отправки запрошенного материала и оценки эффективности источников обращения.</p>

<h2>4. Основание обработки</h2>
<p>Основанием является согласие пользователя, выраженное при отправке формы. Пользователь может отозвать согласие, направив обращение на контактный адрес оператора.</p>

<h2>5. Передача и хранение</h2>
<p>Данные могут передаваться только сервисам, необходимым для работы сайта и обработки обращения: почтовому провайдеру, настроенной CRM или вебхуку и сервису защиты форм от автоматических отправок. Конкретный перечень используемых сервисов необходимо утвердить перед публикацией финальной редакции.</p>

<h2>6. Защита данных</h2>
<p>Оператор ограничивает доступ к заявкам, использует проверку подлинности запросов и применяет организационные и технические меры для предотвращения неправомерного доступа.</p>

<h2>7. Обращения пользователя</h2>
<p>Пользователь вправе запросить сведения об обработке своих данных, их уточнение или удаление, а также отозвать ранее предоставленное согласие.</p>
